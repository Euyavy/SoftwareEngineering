#p - past
#n - now
#a - average price
p = int(input("Введите предыдущее показание: "))
n = int(input("Введите текущее показание: "))
if n >= p:
    i = n - p
else:
    i = 10000 - p + n
if i <= 300:
    cost = 21
elif i <= 600:
    cost = 21 + (i - 300) * 0.06
elif i <= 800:
    cost = 21 + 300 * 0.06 + (i - 600) * 0.04
else:
    cost = (21 + 300 * 0.06 + 200 * 0.04 + (i - 800) * 0.025)
if i > 0:
    a = cost / i
else:
    a = 0
print()
print(f"{'Предыдущее':>12} {'Текущее':>10} "
      f"{'Использовано':>14} {'К оплате':>12} "
      f"{'Ср. цена м3':>13}")
print(f"{p:12d} {n:10d} "
      f"{i:14d} {cost:12.2f} "
      f"{a:13.2f}")
